"""Alert schema and detection response models."""

import uuid
from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field, field_validator


class AlertSeverity(str, Enum):
    """Normalized severity levels for generated security alerts."""
    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"
    CRITICAL = "critical"


class AlertStatus(str, Enum):
    """Lifecycle status of a security alert."""
    OPEN = "open"
    ACKNOWLEDGED = "acknowledged"
    RESOLVED = "resolved"
    CLOSED = "closed"


class Alert(BaseModel):
    """
    Persistent alert generated by the detection engine.
    Carries rule identifiers, supporting evidence, and related event IDs.
    """
    id: str = Field(
        default_factory=lambda: str(uuid.uuid4()),
        description="Unique identifier for the alert",
    )
    rule_id: str = Field(
        ...,
        description="Identifier of the detection rule that triggered this alert (e.g. NG-AUTH-001)",
    )
    title: str = Field(
        ...,
        description="Concise human-readable title of the alert",
    )
    description: str = Field(
        ...,
        description="Detailed description of the detected threat pattern and context",
    )
    severity: AlertSeverity = Field(
        ...,
        description="Severity classification: low, medium, high, critical",
    )
    related_event_ids: List[str] = Field(
        default_factory=list,
        description="IDs of normalized security events supporting this detection",
    )
    evidence: Dict[str, Any] = Field(
        default_factory=dict,
        description="Structured detection evidence (thresholds, timestamps, source IP, etc.)",
    )
    fingerprint: Optional[str] = Field(
        default=None,
        description="Deterministic hash of rule ID and evidence event IDs for duplicate suppression",
    )
    status: AlertStatus = Field(
        default=AlertStatus.OPEN,
        description="Triage status: open, acknowledged, resolved, closed",
    )
    created_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="UTC timestamp when the alert was generated",
    )

    @field_validator("created_at")
    @classmethod
    def ensure_utc_created_at(cls, v: datetime) -> datetime:
        if v.tzinfo is None:
            return v.replace(tzinfo=timezone.utc)
        return v.astimezone(timezone.utc)


class DetectionRunSummary(BaseModel):
    """Summary of a detection execution run."""
    events_evaluated: int = Field(..., description="Total events evaluated during this detection cycle")
    alerts_created: int = Field(..., description="Number of new alerts created and persisted")
    alerts_existing: int = Field(..., description="Number of duplicate alerts identified and suppressed")
    new_alerts: List[Alert] = Field(default_factory=list, description="List of newly generated alerts")
